//! Guest-facing Rust SDK for `mududb` procedures.
//!
//! This crate is the guest side of the MSSP syscall protocol: typed
//! [`Mudu`] entry points serialize requests into MSSP frames
//! ([`mudu_sys`]), the configured backend (native [`adapter`], in-process
//! [`mock`] SQLite emulation, or the wasm32 host imports) executes them, and
//! the [`universal`] DTOs carry results back. See `REGENERATE.md` for how
//! the generated codec under [`universal`] is produced.

#![warn(missing_docs)]

/// Error type returned by the transport and codec layers.
pub mod error;
/// In-process mock backends (SQLite plus in-memory KV/fs emulations).
pub mod mock;
/// Typed guest-facing syscall entry points and their response wrappers.
pub mod mudu;
/// MSSP frame codecs and raw syscall dispatch to the configured backend.
pub mod mudu_sys;
pub mod types;
// The `universal` module tree is WIT-generated code (`mudu_gen` /
// `mudu_api_sync`; every generated file carries a "Generated by ... Do not
// edit manually." header), so missing-docs is allowed for the whole tree
// instead of editing generated files.
#[allow(missing_docs)]
pub mod universal;

pub use error::ApiError;
pub use mock::MockSqliteMuduSysCall;
pub use mudu::{CommandResponse, Mudu, QueryResponse, UniResponse};
pub use types::{UniCommandResult, UniCommandReturn, UniQueryReturn, UniReturn};

pub use universal::uni_command_argv::UniCommandArgv;
pub use universal::uni_data_type::UniDataType;
pub use universal::uni_data_value::UniDataValue;
pub use universal::uni_error::UniError;
pub use universal::uni_fs_dirent::UniFsDirent;
pub use universal::uni_fs_open_argv::UniFsOpenArgv;
pub use universal::uni_fs_stat::UniFsStat;
pub use universal::uni_oid::UniOid;
pub use universal::uni_query_argv::UniQueryArgv;
pub use universal::uni_query_result::UniQueryResult;
pub use universal::uni_record_type::{UniRecordField, UniRecordType};
pub use universal::uni_relation::UniRelationDelta;
pub use universal::uni_result::UniResult;
pub use universal::uni_result_set::UniResultSet;
pub use universal::uni_scalar::UniScalar;
pub use universal::uni_scalar_value::UniScalarValue;
pub use universal::uni_sql_param::UniSqlParam;
pub use universal::uni_sql_stmt::UniSqlStmt;
pub use universal::uni_tuple_row::UniTupleRow;

/// Native adapter transport (separately distributed runtime).
#[cfg(not(target_arch = "wasm32"))]
pub mod adapter;
