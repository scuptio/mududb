//! End-to-end tests for the `mudu_metrics` binary: run it against synthetic
//! source trees and assert on its exit status and report lines.

#![allow(clippy::unwrap_used)]

use mudu_sys::process::Command;
use std::process::Stdio;

fn temp_tree(tag: &str) -> std::path::PathBuf {
    let dir =
        mudu_sys::env_var::temp_dir().join(format!("mudu_metrics_{tag}_{}", std::process::id()));
    let _ = mudu_sys::fs::sync::sync_remove_dir_all(&dir);
    mudu_sys::fs::sync::sync_create_dir_all(&dir).unwrap();
    dir
}

fn run_metrics(args: &[&str]) -> std::process::Output {
    Command::new(env!("CARGO_BIN_EXE_mudu_metrics"))
        .args(args)
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .output()
        .unwrap()
}

#[test]
fn clean_tree_reports_all_files_checked() {
    let dir = temp_tree("clean");
    mudu_sys::fs::sync::sync_write(dir.join("ok.rs"), "fn main() {}\n").unwrap();
    let root = dir.to_str().unwrap().to_string();
    let out = run_metrics(&["--root", &root]);
    assert!(
        out.status.success(),
        "stderr: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(stdout.contains("1 file(s) checked"), "stdout: {stdout}");
    let _ = mudu_sys::fs::sync::sync_remove_dir_all(&dir);
}

#[test]
fn over_long_file_and_item_are_reported() {
    let dir = temp_tree("violation");
    // 8 lines > max_file_lines (5); `f` spans 5 lines > max_function_lines (3).
    mudu_sys::fs::sync::sync_write(
        dir.join("big.rs"),
        "fn f() {\n    let a = 1;\n    let b = 2;\n    let c = a + b;\n    println!(\"{c}\");\n}\n\nfn g() {}\n",
    )
    .unwrap();
    mudu_sys::fs::sync::sync_write(
        dir.join("code_metrics.toml"),
        "max_file_lines = 5\nmax_function_lines = 3\nmax_struct_lines = 100\nmax_class_lines = 100\n",
    )
    .unwrap();
    let root = dir.to_str().unwrap().to_string();
    let out = run_metrics(&["--root", &root]);
    assert!(!out.status.success());
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(
        stdout.contains("file is 8 lines (limit 5)"),
        "stdout: {stdout}"
    );
    assert!(
        stdout.contains("function `f` is 6 lines (limit 3)"),
        "stdout: {stdout}"
    );
    let _ = mudu_sys::fs::sync::sync_remove_dir_all(&dir);
}

#[test]
fn generated_marker_and_exclude_prefix_skip_files() {
    let dir = temp_tree("skip");
    // Generated files are skipped regardless of length.
    let generated = format!(
        "// Generated by test. Do not edit manually.\n{}\n",
        "fn filler() {}\n".repeat(20)
    );
    mudu_sys::fs::sync::sync_write(dir.join("gen.rs"), generated).unwrap();
    // The excluded directory prefix drops everything below it.
    mudu_sys::fs::sync::sync_create_dir_all(dir.join("skipme")).unwrap();
    mudu_sys::fs::sync::sync_write(
        dir.join("skipme").join("long.rs"),
        "fn filler() {}\n".repeat(20),
    )
    .unwrap();
    mudu_sys::fs::sync::sync_write(dir.join("ok.rs"), "fn main() {}\n").unwrap();
    let cfg = dir.join("metrics.toml");
    mudu_sys::fs::sync::sync_write(&cfg, "max_file_lines = 5\nexclude = [\"skipme\"]\n").unwrap();
    let root = dir.to_str().unwrap().to_string();
    let cfg_arg = cfg.to_str().unwrap().to_string();
    let out = run_metrics(&["--root", &root, "--config", &cfg_arg]);
    assert!(
        out.status.success(),
        "stderr: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(
        stdout.contains("1 file(s) checked, 1 excluded, 1 generated skipped"),
        "stdout: {stdout}"
    );
    let _ = mudu_sys::fs::sync::sync_remove_dir_all(&dir);
}

#[test]
fn unparsable_rust_is_a_reported_error() {
    let dir = temp_tree("parse");
    mudu_sys::fs::sync::sync_write(dir.join("broken.rs"), "fn broken( {\n").unwrap();
    let root = dir.to_str().unwrap().to_string();
    let out = run_metrics(&["--root", &root]);
    assert!(!out.status.success());
    let _ = mudu_sys::fs::sync::sync_remove_dir_all(&dir);
}

#[test]
fn report_counts_languages_and_rust_test_split() {
    let dir = temp_tree("report");
    mudu_sys::fs::sync::sync_create_dir_all(dir.join("tests")).unwrap();
    // 7 lines: 2 non-test + a 5-line `#[cfg(test)]` block.
    mudu_sys::fs::sync::sync_write(
        dir.join("lib.rs"),
        "fn a() {}\n\n#[cfg(test)]\nmod t {\n    #[test]\n    fn x() {}\n}\n",
    )
    .unwrap();
    mudu_sys::fs::sync::sync_write(dir.join("tests").join("it.rs"), "fn it() {}\nfn it2() {}\n")
        .unwrap();
    mudu_sys::fs::sync::sync_write(dir.join("tool.py"), "print(1)\n").unwrap();
    let root = dir.to_str().unwrap().to_string();
    let out = run_metrics(&["report", "--root", &root]);
    assert!(
        out.status.success(),
        "stderr: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(stdout.contains("Rust"), "stdout: {stdout}");
    assert!(stdout.contains("Python"), "stdout: {stdout}");
    assert!(stdout.contains("1 blocks, 5 lines"), "stdout: {stdout}");
    assert!(stdout.contains("1 files, 2 lines"), "stdout: {stdout}");
    assert!(
        stdout.contains("non-test:         2 lines"),
        "stdout: {stdout}"
    );
    let _ = mudu_sys::fs::sync::sync_remove_dir_all(&dir);
}
