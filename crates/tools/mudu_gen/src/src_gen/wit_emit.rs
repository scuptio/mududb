//! WIT backend: emit a WIT module from the unified object IR.
//!
//! This is the `wit` backend of the object-definition pipeline. It projects a
//! DDL-declared object (table/queue/type) onto its interface shape:
//! length/precision live only in the DDL/`DataTypeInfo` and are dropped here,
//! and field/record names are projected to kebab-case (pipeline design §4/§6).

use mudu::utils::case_convert::to_kebab_case;
use mudu_binding::table::class_def::ClassDef;
use mudu_binding::universal::uni_data_type::UniDataType;
use mudu_binding::universal::uni_scalar::UniScalar;

/// Renders a full WIT module: `package`, `interface`, and one `record` per
/// object, matching the shape the design (§8) feeds `wasm-tools component
/// embed`.
pub fn emit_wit_module(records: &[ClassDef], package: &str, interface: &str) -> String {
    let mut out =
        String::from("// Generated by mgen (DDL -> WIT projection). Do not edit manually.\n");
    out.push_str(&format!("package {package};\n\ninterface {interface} {{\n"));
    let body = records
        .iter()
        .filter(|record| !record.kind().is_cache())
        .map(|record| emit_record(record, 1))
        .collect::<Vec<_>>()
        .join("\n\n");
    out.push_str(&body);
    out.push_str("\n}\n");
    out
}

/// Renders a single object as an indented WIT `record`.
fn emit_record(record: &ClassDef, indent: usize) -> String {
    let pad = "    ".repeat(indent);
    let name = to_kebab_case(record.class_name());
    let mut out = format!("{pad}record {name} {{\n");
    for column in record.table_columns() {
        let field_name = to_kebab_case(column.column_name());
        let ty = wit_type(column.data_type());
        let ty = if column.is_not_null() {
            ty
        } else {
            format!("option<{ty}>")
        };
        out.push_str(&format!("{pad}    {field_name}: {ty},\n"));
    }
    out.push_str(&format!("{pad}}}"));
    out
}

/// Maps a universal data type onto its WIT type name.
fn wit_type(ty: &UniDataType) -> String {
    match ty {
        UniDataType::Scalar(scalar) => scalar_wit_name(scalar),
        UniDataType::Array(inner) => format!("list<{}>", wit_type(inner)),
        UniDataType::Option(inner) => format!("option<{}>", wit_type(inner)),
        UniDataType::Struct(record) => to_kebab_case(&record.struct_name),
        UniDataType::Tuple(items) => {
            let inner = items.iter().map(wit_type).collect::<Vec<_>>().join(", ");
            format!("tuple<{inner}>")
        }
        UniDataType::Result(result) => {
            let ok = result
                .ok
                .as_deref()
                .map(wit_type)
                .unwrap_or_else(|| "_".to_string());
            let err = result
                .err
                .as_deref()
                .map(wit_type)
                .unwrap_or_else(|| "_".to_string());
            format!("result<{ok}, {err}>")
        }
        UniDataType::Identifier(name) => name.clone(),
        UniDataType::Binary => "list<u8>".to_string(),
        UniDataType::Box(inner) => wit_type(inner),
    }
}

/// Maps a scalar onto its WIT type name.
fn scalar_wit_name(scalar: &UniScalar) -> String {
    match scalar {
        UniScalar::Bool => "bool",
        UniScalar::U8 => "u8",
        UniScalar::I8 => "i8",
        UniScalar::U16 => "u16",
        UniScalar::I16 => "i16",
        UniScalar::U32 => "u32",
        UniScalar::I32 => "i32",
        UniScalar::U64 => "u64",
        UniScalar::U128 => "u128",
        UniScalar::I64 => "i64",
        UniScalar::I128 => "i128",
        UniScalar::F32 => "f32",
        UniScalar::F64 => "f64",
        UniScalar::Char => "char",
        UniScalar::String => "string",
        UniScalar::Blob => "list<u8>",
        UniScalar::Numeric => "numeric",
        UniScalar::Date => "date",
        UniScalar::Time => "time",
        UniScalar::Timestamp => "timestamp",
        UniScalar::TimestampTz => "timestamp-tz",
    }
    .to_string()
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]
mod tests {
    use super::*;

    fn parse(text: &str) -> Vec<ClassDef> {
        let parser = sql_parser::parser::ddl_parser::DDLParser::new().unwrap();
        parser.parse(text).unwrap()
    }

    #[test]
    fn emits_kebab_case_record_and_fields() {
        let records = parse(
            "CREATE TABLE players(id BIGINT PRIMARY KEY, display_name VARCHAR(32) NOT NULL);",
        );
        let wit = emit_wit_module(&records, "mududb:browserquest", "types");
        assert_eq!(
            wit,
            "// Generated by mgen (DDL -> WIT projection). Do not edit manually.\npackage mududb:browserquest;\n\ninterface types {\n    record players {\n        id: i64,\n        display-name: string,\n    }\n}\n"
        );
    }

    #[test]
    fn nullable_column_projects_to_option() {
        let records = parse("CREATE TABLE t(id INT PRIMARY KEY, tag TEXT);");
        let wit = emit_wit_module(&records, "mududb:test", "types");
        assert!(
            wit.contains("    record t {\n        id: i32,\n        tag: option<string>,\n    }")
        );
    }

    #[test]
    fn multiple_objects_are_separated_by_blank_line() {
        let records =
            parse("CREATE TABLE a(id INT PRIMARY KEY); CREATE TABLE b(name TEXT NOT NULL);");
        let wit = emit_wit_module(&records, "mududb:test", "types");
        assert!(wit.contains(
            "    record a {\n        id: i32,\n    }\n\n    record b {\n        name: string,\n    }"
        ));
    }
}
