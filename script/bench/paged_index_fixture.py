#!/usr/bin/env python3
"""Regenerate the fixed MBP1 leaf fixture using an independent CRC32C encoder."""
from pathlib import Path
import struct


def crc32c(data):
    """Reference reflected Castagnoli CRC, independent of the Rust library."""
    crc = 0xFFFFFFFF
    for byte in data:
        crc ^= byte
        for _ in range(8):
            crc = (crc >> 1) ^ (0x82F63B78 if crc & 1 else 0)
    return crc ^ 0xFFFFFFFF


def main():
    assert crc32c(b"123456789") == 0xE3069283
    page = bytearray(512)
    page[:4] = b"MBP1"
    struct.pack_into("<Q", page, 24, 5)  # Node revision.
    struct.pack_into("<HH", page, 32, 2, 8)  # Slots and prefix length.
    struct.pack_into("<Q", page, 48, 1)  # Logical page ID.
    page[56:64] = (7).to_bytes(8, "big")  # Complete key stored as the prefix.
    struct.pack_into("<HHHH", page, 64, 512, 0, 480, 32)
    struct.pack_into("<QQQQ", page, 480, 0x11223344, 9, 0, 8)
    struct.pack_into("<Q", page, 40, crc32c(page[:40] + page[48:]))
    destination = Path(__file__).resolve().parents[2] / "crates/db-kernel/index/src/paged/fixtures/v1_leaf.hex"
    header = "# Generated by script/bench/paged_index_fixture.py. Do not edit manually.\n"
    destination.write_text(header + "\n".join(page[i:i + 32].hex(" ") for i in range(0, 512, 32)) + "\n")


if __name__ == "__main__":
    main()
