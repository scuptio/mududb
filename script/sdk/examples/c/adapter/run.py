"""Compile the same wallet procedures against native instead of Wasm imports."""
from pathlib import Path
import os
import shutil
import subprocess
import sys
here=Path(__file__).resolve().parent
sdk=here.parents[2]
work=here.parent/'target/adapter-c';work.mkdir(parents=True,exist_ok=True)
source=(here.parent/'mpk/src/mudu_sys.c').read_text()
start=source.index('/* ---- minimal freestanding runtime ---- */')
end=source.index('/* ---- small helpers ---- */')
source=source[:start]+'#include "native_host.h"\n'+source[end:]
source=source.replace('uint8_t ret_area[8];','uint8_t ret_area[sizeof(void*)+4];').replace('memcpy(&frame, ret_area, 4);','memcpy(&frame, ret_area, sizeof(frame));').replace('ret_area + 4, 4','ret_area + sizeof(frame), 4')
(work/'native_sys.c').write_text('/* Generated by adapter/run.py. Do not edit manually. */\n'+source)
binary=work/('wallet.exe' if os.name=='nt' else 'wallet')
command=['clang','-std=c11','-Wall','-Wextra','-Werror',f'-I{sdk}',f'-I{here}',f'-I{here.parent/"mpk/src"}',str(work/'native_sys.c'),str(here.parent/'mpk/src/procedures.c'),str(here/'main.c'),str(sdk/'mududb/codec/mpack.c'),str(sdk/'mududb/codec/mpack_alloc.c'),str(sdk/'mududb/codec/record_bridge.c'),'-o',str(binary)]
if sys.platform=='linux':command+=['-ldl']
subprocess.run(command,check=True)
subprocess.run([str(binary),*sys.argv[1:]],check=True)
