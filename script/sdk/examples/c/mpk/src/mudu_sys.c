/* ---- minimal freestanding runtime ---- */

void *memcpy(void *dst, const void *src, size_t n) {
    uint8_t *d = (uint8_t *)dst;
    const uint8_t *s = (const uint8_t *)src;
    size_t i;
    for (i = 0; i < n; i++) {
        d[i] = s[i];
    }
    return dst;
}

void *memmove(void *dst, const void *src, size_t n) {
    uint8_t *d = (uint8_t *)dst;
    const uint8_t *s = (const uint8_t *)src;
    size_t i;
    if ((uintptr_t)d < (uintptr_t)s) {
        for (i = 0; i < n; i++) {
            d[i] = s[i];
        }
    } else {
        for (i = n; i > 0; i--) {
            d[i - 1] = s[i - 1];
        }
    }
    return dst;
}

void *memset(void *dst, int c, size_t n) {
    uint8_t *d = (uint8_t *)dst;
    size_t i;
    for (i = 0; i < n; i++) {
        d[i] = (uint8_t)c;
    }
    return dst;
}

int memcmp(const void *a, const void *b, size_t n) {
    const uint8_t *x = (const uint8_t *)a;
    const uint8_t *y = (const uint8_t *)b;
    size_t i;
    for (i = 0; i < n; i++) {
        if (x[i] != y[i]) {
            return (int)x[i] - (int)y[i];
        }
    }
    return 0;
}

size_t strlen(const char *s) {
    size_t n = 0;
    while (s[n]) {
        n++;
    }
    return n;
}

/* Bump allocator over linear memory, starting at the linker-provided
 * `__heap_base`; grows the memory on demand. */
extern uint8_t __heap_base;

static uint8_t *arena_cur;

void *mudu_arena_alloc(size_t size, size_t align) {
    uintptr_t p;
    size_t avail;
    if (!arena_cur) {
        arena_cur = &__heap_base;
    }
    if (align < 1) {
        align = 1;
    }
    p = ((uintptr_t)arena_cur + (align - 1)) & ~(uintptr_t)(align - 1);
    avail = __builtin_wasm_memory_size(0) * (size_t)65536 - (size_t)p;
    if (size > avail) {
        size_t pages = (size - avail + 65535) / 65536;
        if (__builtin_wasm_memory_grow(0, pages) == (size_t)-1) {
            return 0;
        }
    }
    arena_cur = (uint8_t *)(p + size);
    return (void *)p;
}

/*
 * Canonical-ABI realloc: the lift glue generated by `wasm-tools component
 * new` calls this to place incoming lists (procedure params, syscall
 * replies) in guest memory. `cabi_realloc` is the current export name;
 * `canonical_abi_realloc` is the pre-rename alias older toolchains look up.
 */
__attribute__((export_name("cabi_realloc"))) void *
cabi_realloc(void *old_ptr, size_t old_size, size_t align, size_t new_size) {
    void *p = mudu_arena_alloc(new_size, align);
    if (old_ptr && p) {
        memcpy(p, old_ptr, old_size < new_size ? old_size : new_size);
    }
    return p;
}

__attribute__((export_name("canonical_abi_realloc"))) void *
canonical_abi_realloc(void *old_ptr, size_t old_size, size_t align, size_t new_size) {
    return cabi_realloc(old_ptr, old_size, align, new_size);
}

/* `realloc`/`free` behind the binding's default `mp_realloc`
 * (mpack_alloc.c): every allocation carries a 16-byte header with its size
 * so `realloc` can copy the old payload; `free` is a no-op because the bump
 * arena is never partially released. The 16-byte header keeps payloads
 * 16-byte aligned, satisfying the strictest C alignment requirement. */
typedef struct {
    uint64_t size;
    uint64_t reserved;
} mudu_alloc_header;

void *realloc(void *old_ptr, size_t new_size) {
    mudu_alloc_header *header;
    if (new_size == 0) {
        return 0;
    }
    header = (mudu_alloc_header *)mudu_arena_alloc(sizeof(mudu_alloc_header) + new_size, 16);
    if (!header) {
        return 0;
    }
    header->size = new_size;
    header->reserved = 0;
    if (old_ptr) {
        const mudu_alloc_header *old_header = ((const mudu_alloc_header *)old_ptr) - 1;
        size_t n = old_header->size < new_size ? old_header->size : new_size;
        memcpy(header + 1, old_ptr, n);
    }
    return (void *)(header + 1);
}

void free(void *ptr) {
    (void)ptr;
}

