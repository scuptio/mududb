/*
 * Syscall layer for the wallet-c guest — see mudu_sys.h for the API
 * contract. Unlike the mpm-crate C template (which hand-rolls the MSSP
 * frame and the `uni` MessagePack shapes), every wire encode/decode here
 * goes through the formal C binding: `mududb/codec/mpack.{h,c}` for the
 * MessagePack runtime and the generated `mududb/types/Uni*.h` codecs for
 * the MSSP v1 frames, the SyscallPayload request/result bodies and the
 * procedure byte-pipe shapes. The binding sources are compiled straight
 * from `crates/sdk/bindings/c` (see Makefile.toml) — nothing is vendored.
 *
 * The procedure byte pipe (the `mp2-*` exports wired in the mtp-generated
 * procedures_gen.c) is NOT MSSP-framed: the host passes a bare MessagePack
 * `UniProcedureParam` (record-as-map) and expects the hand-written
 * `UniResult<UniProcedureResult, UniError>` shape back — a single-entry
 * map, key 0 for the ok value and key 1 for the error (see
 * `mudu_binding::universal::uni_result::UniResult` on the host).
 *
 * Ownership: the binding's decode arena and writer buffers allocate through
 * `mp_realloc` (mpack_alloc.c) -> `realloc`, which the freestanding runtime
 * below backs with the guest bump arena. Decoded values therefore live
 * until the guest call ends; nothing is individually freed (`free` is a
 * no-op), which matches the short-lived procedure-call model.
 */
