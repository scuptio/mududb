"""Stage shared Wallet sources for a native Go build (no Wasm toolchain needed)."""
from pathlib import Path
import os
import shutil
import subprocess
import sys
here=Path(__file__).resolve().parent
sdk=here.parents[2]
work=here.parent/'target/adapter-go'
work.mkdir(parents=True,exist_ok=True)
source=(here.parent/'mpk/mudusys.go').read_text()
source=source.replace('\t"wallet_go/binding/mududb/api/system"\n','').replace('\t"go.bytecodealliance.org/cm"\n','')
for operation in ('Query','Command'):
    source=source.replace(f'response := system.{operation}(cm.ToList(frame))',f'response, err := invoke("{operation.lower()}", frame)\n\tif err != nil {{ return '+('nil' if operation=='Query' else '0')+', err }').replace('response.Slice()', 'response')
(work/'mudusys.go').write_text('// Generated by adapter/run.py. Do not edit manually.\n'+source)
for origin,name in [(here/'main.go','main.go'),(here.parent/'mpk/procedures.go','procedures.go'),(here.parent/'mpk/sql/ddl.sql','ddl.sql')]:shutil.copyfile(origin,work/name)
# Quoted module replacements preserve spaces in SDK paths.
import json
(work/'go.mod').write_text('module wallet_adapter\n\ngo 1.24\n\nrequire github.com/mududb/mududb-go v0.0.0\nreplace github.com/mududb/mududb-go => '+json.dumps(sdk.as_posix())+'\n')
env=os.environ.copy();env['GOWORK']='off';env['CGO_ENABLED']='1'
subprocess.run(['go','run','.',*sys.argv[1:]],cwd=work,env=env,check=True)
