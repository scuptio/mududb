#!/usr/bin/env python3
"""Regenerate the six-language binding codecs with mgen and sync them into the
checkout, deleting only files that carry the generated marker.

The generated trees mix generated files with hand-written ones (e.g. the Go
`types/` directory also holds `struct_bridge.go` and `wire.go`), so a blanket
`rm` of the destination is unsafe. This script owns deletion and applies it
only to files whose content starts with the "Generated by mudu_gen" marker;
hand-written files are never touched.

The read-only byte-compare gate lives in `script/ci/check_bindings_regen.py`
and stays the CI check; this script is the write path.
"""
import json
from pathlib import Path
import shutil
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'ci'))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'sdk'))

from check_bindings_regen import generator_environment
from tooling import executable_name, run

ROOT = Path(__file__).resolve().parents[2]

GENERATED_MARKER = b'Generated by mudu_gen. Do not edit manually.'


def is_generated(path):
    """Whether the file carries the generated marker (and may be deleted)."""
    if not path.is_file():
        return False
    return GENERATED_MARKER in path.read_bytes()[:256]


def sync_generated(generated_dir, destination, pattern, rewrite=None, exclude=()):
    """Sync `pattern` files from `generated_dir` into `destination`: copies
    every generated file and deletes stale destination files that still carry
    the generated marker. Returns (written, removed) names."""
    written = []
    fresh = {}
    for file in sorted(generated_dir.glob(pattern)):
        if file.name in exclude:
            continue
        content = file.read_bytes()
        if rewrite:
            content = rewrite(content)
        target = destination / file.name
        if not target.is_file() or target.read_bytes() != content:
            target.write_bytes(content)
            written.append(file.name)
        fresh[file.name] = True
    removed = []
    for existing in sorted(destination.glob(pattern)):
        if existing.name not in fresh and is_generated(existing):
            existing.unlink()
            removed.append(existing.name)
    return written, removed


def main():
    workspace = ROOT / 'crates/tools'
    env, host = generator_environment(ROOT)
    run(['cargo', 'build', '-q', '-p', 'mudu_gen', '--bin', 'mgen', '--target', host],
        workspace, env)
    metadata = json.loads(
        run(['cargo', 'metadata', '--no-deps', '--format-version', '1'], workspace, env,
            capture=True))
    mgen = Path(metadata['target_directory']) / host / 'debug' / executable_name('mgen')
    wit = ROOT / 'crates/common/mudu_binding/wit'

    with tempfile.TemporaryDirectory(prefix='sdk-regen-') as tmp:
        # C# → uni/*.cs (mududb.types); UniSyscall.cs routes to mudu_sys/.
        output = Path(tmp) / 'csharp'
        run([mgen, 'message', '-i', wit, '-o', output, '-l', 'csharp', '--with-func-codec'],
            ROOT, env)
        written, removed = sync_generated(output, ROOT / 'crates/sdk/mudu_api/csharp/uni',
                                          'Uni*.cs', exclude={'UniSyscall.cs'})
        syscall = output / 'UniSyscall.cs'
        target = ROOT / 'crates/sdk/mudu_api/csharp/mudu_sys/UniSyscall.cs'
        if not target.is_file() or target.read_bytes() != syscall.read_bytes():
            shutil.copyfile(syscall, target)
            written.append('mudu_sys/UniSyscall.cs')
        print(f'csharp: {len(written)} written, {len(removed)} removed')

        # Python → mududb/generated/ (plus the syscall schema descriptor).
        output = Path(tmp) / 'python'
        run([mgen, 'message', '-i', wit, '-o', output, '-l', 'python', '--with-func-codec'],
            ROOT, env)
        written, removed = sync_generated(
            output, ROOT / 'crates/sdk/bindings/python/mududb/generated', '*.py')
        schema_src = (ROOT / 'crates/common/mudu_binding/src/codec/syscall_payload'
                      / 'syscall_schema.desc.json')
        schema_dst = (ROOT / 'crates/sdk/bindings/python/mududb/generated'
                      / 'syscall_schema.desc.json')
        if not schema_dst.is_file() or schema_dst.read_bytes() != schema_src.read_bytes():
            shutil.copyfile(schema_src, schema_dst)
            written.append('syscall_schema.desc.json')
        print(f'python: {len(written)} written, {len(removed)} removed')

        # AssemblyScript → assembly/generated/ (the mpack import path moves up
        # one level from the generator's flat output).
        output = Path(tmp) / 'assemblyscript'
        run([mgen, 'message', '-i', wit, '-o', output, '-l', 'assemblyscript',
             '--with-func-codec'], ROOT, env)
        written, removed = sync_generated(
            output, ROOT / 'crates/sdk/bindings/assemblyscript/assembly/generated', '*.ts',
            rewrite=lambda content: content.replace(b'from "./mpack"', b'from "../mpack"'))
        print(f'assemblyscript: {len(written)} written, {len(removed)} removed')

        # Go → types/ (package types; wire.go and struct_bridge*.go are
        # hand-written and untouched — they carry no generated marker).
        output = Path(tmp) / 'go'
        run([mgen, 'message', '-i', wit, '-o', output, '-l', 'go', '--with-func-codec'],
            ROOT, env)
        written, removed = sync_generated(output, ROOT / 'crates/sdk/bindings/go/types',
                                          'Uni*.go')
        print(f'go: {len(written)} written, {len(removed)} removed')

        # C → mududb/types/ (mududb/codec is hand-written and untouched).
        output = Path(tmp) / 'c'
        run([mgen, 'message', '-i', wit, '-o', output, '-l', 'c', '--with-func-codec'],
            ROOT, env)
        written, removed = sync_generated(output, ROOT / 'crates/sdk/bindings/c/mududb/types',
                                          'Uni*.h')
        print(f'c: {len(written)} written, {len(removed)} removed')


if __name__ == '__main__':
    main()
