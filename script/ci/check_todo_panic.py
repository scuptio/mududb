#!/usr/bin/env python3
"""Report the TODO / panic-surface surface of production code (advisory).

This gate measures two signals over the repository's hand-written Rust code and
prints a per-crate report — it never fails, so it acts as a trend indicator
rather than a blocker:

  * `todo`  — `TODO` / `FIXME` / `HACK` / `XXX` markers found in comments, and
  * `panic` — the panic surface: `unwrap()`, `expect(...)`, `panic!`,
    `todo!`, `unimplemented!` and `unreachable!` occurrences.

What is scanned:

  * `crates/**/*.rs` and `example/**/*.rs`, grouped by the nearest containing
    `Cargo.toml` (the crate is keyed by its manifest dir relative to the repo
    root, e.g. `crates/common/mudu`).

What is deliberately excluded (all "not production code"):

  * generated files — the header carries the canonical
    `Generated by ... Do not edit manually.` marker (same convention as
    `mudu_metrics`), plus the SpacetimeDB client bindings under
    `example/mpk/tpcc/spacetimedb` whose generator does not emit that marker;
  * the `testing` and `catalog-testing` crates and the fuzz targets;
  * standalone test files — anything under a `tests/` directory or named
    `*_test.rs` / `test_*.rs`;
  * in-crate `#[cfg(test)]` items — modules, functions, impls, uses, statics
    and consts guarded by a test cfg (including `cfg(any(test, ...))` and
    `cfg(all(test, ...))`), so unit tests do not leak into the report.

The scan is a small Rust lexer (strings, chars, nested block comments and
attributes are understood, so `unwrap` inside a string or comment is not
counted). It is deterministic: the same tree always yields the same numbers.

Exit 0 always.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parents[2]

# Directories (relative to the repo root) whose crates are never scanned.
EXCLUDED_CRATE_DIRS = {
    "crates/db-kernel/testing",
    "crates/db-kernel/catalog-testing",
    # Fuzz targets link the test-instrumented kernel and are build/test
    # scaffolding, not shipped code.
    "crates/db-kernel/mudu_kernel/fuzz",
}

# Files / directory prefixes excluded even though their header is not the
# canonical generated marker (mirrors code_metrics.toml `exclude`).
EXTRA_EXCLUDED_PREFIXES = ("example/mpk/tpcc/spacetimedb",)

TODO_MARKERS = ("TODO", "FIXME", "HACK", "XXX")
PANIC_MACROS = {"panic", "todo", "unimplemented", "unreachable"}
PANIC_METHODS = {"unwrap", "expect"}

# Item keywords whose bodies are `{ ... }` blocks.
BLOCK_ITEM_KEYWORDS = {"mod", "fn", "impl", "trait", "struct", "enum", "union"}
# Item keywords terminated by a top-level `;`.
SEMI_ITEM_KEYWORDS = {"use", "type", "const", "static"}
# Keywords allowed between a `#[cfg(test)]` attribute and the item keyword.
MODIFIER_KEYWORDS = {"pub", "unsafe", "async", "const", "extern", "default"}


class Token:
    __slots__ = ("kind", "text")

    def __init__(self, kind: str, text: str):
        self.kind = kind
        self.text = text


def match_string(s: str, i: int) -> Optional[int]:
    """Return the index just past a string literal starting at `i`, or None."""
    n = len(s)
    j = i
    if j < n and s[j] in "bB":
        j += 1
    raw = False
    if j < n and s[j] in "rR":
        raw = True
        j += 1
    if raw:
        hashes = 0
        while j < n and s[j] == "#":
            hashes += 1
            j += 1
        if j >= n or s[j] != '"':
            return None
        j += 1
        while j < n:
            if s[j] == '"':
                k = j + 1
                cnt = 0
                while k < n and s[k] == "#" and cnt < hashes:
                    cnt += 1
                    k += 1
                if cnt == hashes:
                    return k
            j += 1
        return None
    if j >= n or s[j] != '"':
        return None
    j += 1
    while j < n:
        if s[j] == "\\":
            j += 2
            continue
        if s[j] == '"':
            return j + 1
        j += 1
    return None


def tokenize(source: str) -> List[Token]:
    """Lex a Rust source file into the token subset this gate cares about."""
    tokens: List[Token] = []
    n = len(source)
    i = 0
    while i < n:
        ch = source[i]

        if ch.isspace():
            i += 1
            continue

        if source.startswith("//", i):
            j = source.find("\n", i)
            if j == -1:
                j = n
            tokens.append(Token("LineComment", source[i:j]))
            i = j
            continue

        if source.startswith("/*", i):
            j = i + 2
            depth = 1
            while j < n and depth > 0:
                if source.startswith("/*", j):
                    depth += 1
                    j += 2
                elif source.startswith("*/", j):
                    depth -= 1
                    j += 2
                else:
                    j += 1
            tokens.append(Token("BlockComment", source[i:j]))
            i = j
            continue

        if ch in "bBrR\"":
            end = match_string(source, i)
            if end is not None:
                tokens.append(Token("Str", source[i:end]))
                i = end
                continue

        if ch == "'":
            j = i + 1
            if j < n and source[j] == "\\":
                while j < n and source[j] != "'":
                    j += 1
                j += 1
            elif j < n and source[j] == "'":
                j += 1
            elif j + 1 < n and source[j + 1] == "'":
                j += 2
            else:
                while j < n and (source[j].isalnum() or source[j] == "_"):
                    j += 1
            tokens.append(Token("Char", source[i:j]))
            i = j
            continue

        if source.startswith("#[", i):
            j = i + 2
            depth = 1
            while j < n and depth > 0:
                if source[j] == '"':
                    end = match_string(source, j)
                    if end is not None:
                        j = end
                        continue
                if source[j] == "[":
                    depth += 1
                elif source[j] == "]":
                    depth -= 1
                    if depth == 0:
                        j += 1
                        break
                j += 1
            tokens.append(Token("Attr", source[i:j]))
            i = j
            continue

        if ch.isalpha() or ch == "_":
            j = i + 1
            while j < n and (source[j].isalnum() or source[j] == "_"):
                j += 1
            tokens.append(Token("Ident", source[i:j]))
            i = j
            continue

        tokens.append(Token("Punct", ch))
        i += 1

    return tokens


def cfg_contains_test(attr_text: str) -> bool:
    """Whether a `#[cfg(...)]` attribute is true when `test` is set."""
    inner = attr_text[attr_text.find("[") + 1 : attr_text.rfind("]")]
    # Drop string literals so `feature = "test"` never reads as the test cfg.
    cleaned = ""
    i = 0
    while i < len(inner):
        if inner[i] == '"':
            end = match_string(inner, i)
            if end is None:
                break
            cleaned += '""'
            i = end
        else:
            cleaned += inner[i]
            i += 1
    # `not(test)` guards production code; remove it before looking for a bare
    # `test` predicate.
    cleaned = cleaned.replace("not(test)", "").replace("not (test)", "")
    for part in cleaned.replace("(", " ").replace(")", " ").replace(",", " ").split():
        if part == "test":
            return True
    return False


def is_punct(tokens: List[Token], idx: int, text: str) -> bool:
    return idx < len(tokens) and tokens[idx].kind == "Punct" and tokens[idx].text == text


def skip_cfg_test_item(tokens: List[Token], start: int) -> int:
    """Skip the item that follows a `#[cfg(test)]` attribute (inclusive).

    `start` points at the Attr token; returns the index of the first token
    after the guarded item.
    """
    j = start + 1
    while j < len(tokens) and tokens[j].kind in ("Attr", "LineComment", "BlockComment"):
        j += 1
    while j < len(tokens):
        t = tokens[j]
        if t.kind == "Ident" and t.text in MODIFIER_KEYWORDS:
            j += 1
            # `pub(crate)` / `pub(in path)` visibility takes a parenthesised
            # suffix; skip it so it is not mistaken for a block opener.
            if t.text == "pub" and is_punct(tokens, j, "("):
                depth = 0
                while j < len(tokens):
                    if is_punct(tokens, j, "("):
                        depth += 1
                    elif is_punct(tokens, j, ")"):
                        depth -= 1
                        if depth == 0:
                            j += 1
                            break
                    j += 1
            continue
        break

    if j >= len(tokens):
        return start + 1
    keyword = tokens[j].text if tokens[j].kind == "Ident" else ""

    if keyword in SEMI_ITEM_KEYWORDS:
        depth = 0
        j += 1
        while j < len(tokens):
            if is_punct(tokens, j, "{"):
                depth += 1
            elif is_punct(tokens, j, "}"):
                depth -= 1
            elif is_punct(tokens, j, ";") and depth == 0:
                return j + 1
            j += 1
        return j

    if keyword in BLOCK_ITEM_KEYWORDS:
        while j < len(tokens) and not is_punct(tokens, j, "{"):
            j += 1
        depth = 0
        while j < len(tokens):
            if is_punct(tokens, j, "{"):
                depth += 1
            elif is_punct(tokens, j, "}"):
                depth -= 1
                if depth == 0:
                    return j + 1
            j += 1
        return j

    # Unknown item shape: only drop the attribute itself rather than risk
    # skipping production code.
    return start + 1


def analyze(source: str) -> Tuple[int, int]:
    """Return `(todo_count, panic_count)` for one source file."""
    tokens = tokenize(source)
    todo = 0
    panic = 0
    i = 0
    while i < len(tokens):
        t = tokens[i]
        kind = t.kind
        if kind in ("LineComment", "BlockComment"):
            upper = t.text.upper()
            todo += sum(1 for m in TODO_MARKERS if m in upper)
        elif kind == "Attr":
            if cfg_contains_test(t.text):
                i = skip_cfg_test_item(tokens, i)
                continue
        elif kind == "Ident":
            nxt = i + 1
            while nxt < len(tokens) and tokens[nxt].kind in ("LineComment", "BlockComment"):
                nxt += 1
            if nxt < len(tokens) and tokens[nxt].kind == "Punct":
                if t.text in PANIC_METHODS and tokens[nxt].text == "(":
                    panic += 1
                elif t.text in PANIC_MACROS and tokens[nxt].text == "!":
                    panic += 1
        i += 1
    return todo, panic


def find_crate_for(path: Path) -> Optional[Path]:
    """Return the manifest dir (relative to ROOT) owning `path`, if any."""
    for parent in [path.parent, *path.parent.parents]:
        if (parent / "Cargo.toml").exists():
            return parent.relative_to(ROOT)
    return None


def is_generated(source: str) -> bool:
    return any(
        "Generated by" in line and "Do not edit manually." in line
        for line in source.splitlines()[:10]
    )


def is_test_file(relative: Path) -> bool:
    parts = relative.parts
    if "tests" in parts:
        return True
    name = relative.name
    return name.startswith("test_") or name.endswith("_test.rs")


def collect() -> Dict[str, Dict[str, int]]:
    """Scan the tree and return `{crate_key: {"todo": n, "panic": n}}`."""
    results: Dict[str, Dict[str, int]] = {}
    for root in ("crates", "example"):
        for path in sorted((ROOT / root).rglob("*.rs")):
            relative = path.relative_to(ROOT)
            rel_str = str(relative)
            if "target" in relative.parts or ".git" in relative.parts:
                continue
            if any(rel_str.startswith(prefix) for prefix in EXTRA_EXCLUDED_PREFIXES):
                continue
            if is_test_file(relative):
                continue
            crate = find_crate_for(path)
            if crate is None or str(crate) in EXCLUDED_CRATE_DIRS:
                continue
            source = path.read_text(encoding="utf-8")
            if is_generated(source):
                continue
            todo, panic = analyze(source)
            key = str(crate)
            entry = results.setdefault(key, {"todo": 0, "panic": 0})
            entry["todo"] += todo
            entry["panic"] += panic
    return results


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--sort",
        choices=("panic", "todo", "crate"),
        default="panic",
        help="sort order for the per-crate report (default: %(default)s)",
    )
    args = parser.parse_args()

    results = collect()
    rows = sorted(
        results.items(),
        key=lambda kv: (
            -kv[1]["panic"] if args.sort == "panic" else 0,
            -kv[1]["todo"] if args.sort == "todo" else 0,
            kv[0],
        ),
    )

    total_todo = sum(v["todo"] for v in results.values())
    total_panic = sum(v["panic"] for v in results.values())
    width = max((len(k) for k in results), default=0)

    print(f"{'crate':<{width}}  {'todo':>6}  {'panic':>6}")
    print(f"{'-' * width}  {'-' * 6}  {'-' * 6}")
    for key, value in rows:
        if value["todo"] == 0 and value["panic"] == 0:
            continue
        print(f"{key:<{width}}  {value['todo']:>6}  {value['panic']:>6}")
    print(f"{'-' * width}  {'-' * 6}  {'-' * 6}")
    print(
        f"{'total':<{width}}  {total_todo:>6}  {total_panic:>6}  "
        f"({len(results)} crate(s) scanned)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
