#!/usr/bin/env python3
"""Distributed e2e: one container per endpoint, real sockets over a bridge
network, running the real `mudud` binary plus a client-side driver.

Consolidates the former `run_distributed_e2e.sh` (orchestration) and
`gen_cluster_config.py` (per-node config generation) into a single harness.

Usage: cargo make test-e2e-distributed            # run every scenario
       cargo make test-e2e-distributed -- --scenario raft
       cargo make test-e2e-distributed -- --scenario single-node,stream

The client-side driver stays in Rust (testing/tests/test_distributed_driver.rs):
it exercises the real `mudu_client` TCP client, which has no Python host
equivalent (the pgwire surface is only served by the legacy backend, not the
Tokio kernel backend the deployment shapes use).
"""

import argparse
import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO_ROOT / "script/lib"))
from task_report import Report, add_options
from cli import normalized_argv

E2E_DIR = REPO_ROOT / "script" / "test" / "e2e"
CONFIGS_DIR = E2E_DIR / "configs"
DEV_IMAGE = "mududb-dev:local"
E2E_IMAGE = "mududb-e2e:local"

# ---------------------------------------------------------------------------
# Per-node `mudud` config generation (previously gen_cluster_config.py).
#
# Each node is deployed as its own container (`mudud serve -c <name>.toml`),
# so every generated file is a complete, self-contained server config using
# the current config contract (top-level `version = 1` + `name`/`cluster` plus
# the `control_plane` / `data_plane` sections with name-derived identity). Peer
# hostnames resolve through the Docker bridge network's DNS.
#
# Scenarios (--scenario):
#   single-node   one self-contained node, no `data_plane` (no replication)
#   raft          one data group (a single DRS), Raft, Combined (no control_plane)
#   stream        one data group (a single DRS), stream replication
#   scale-out     a dedicated control plane plus multiple Raft data groups
# ---------------------------------------------------------------------------

# Fixed ports. Every node is its own container, so the same numbers are reused
# across nodes; only the hostname differs. Kept clear of the worker multi-port
# range so the replication/channel listeners never collide with client ports.
HTTP_PORT = 8300
PG_PORT = 5432
TCP_PORT = 9527
REPL_PORT = 9600
CHANNEL_PORT = 9601
CLUSTER_NAME = "e2e"
WORKER_THREADS = 2


def _header(name: str) -> str:
    return f"""# Generated by distributed_e2e.py — do not edit by hand.
mpk_path = "/data/mpk"
db_path = "/data/{name}"
listen_ip = "0.0.0.0"
http_listen_port = {HTTP_PORT}
pg_listen_port = {PG_PORT}
tcp_listen_port = {TCP_PORT}
worker_threads = {WORKER_THREADS}
enable_async = true
server_mode = "Tokio"
version = 1
"""


def _member(name: str) -> str:
    return (
        "[[data_plane.group.replica.member]]\n"
        f'name = "{name}"\n'
        f'host = "{name}"\n'
        f"channel_port = {CHANNEL_PORT}\n"
        f"client_port = {PG_PORT}\n"
        f"replication_port = {REPL_PORT}\n"
    )


def _control_member(name: str) -> str:
    return (
        "[[control_plane.replica.member]]\n"
        f'name = "{name}"\n'
        f'host = "{name}"\n'
        f"channel_port = {CHANNEL_PORT}\n"
        f"client_port = {PG_PORT}\n"
    )


def _identity(name: str) -> str:
    return (
        f'name = "{name}"\n'
        f'cluster = "{CLUSTER_NAME}"\n'
        f"channel_listen_port = {CHANNEL_PORT}\n"
        "topology_version = 1\n"
    )


def _group(name: str, mode: str, members: list) -> str:
    if mode == "raft":
        mode_block = "[data_plane.group.replica.raft]\ntick_ms = 25\nelection_timeout_ticks = 4\n"
    else:
        mode_block = (
            "[data_plane.group.replica.stream]\n"
            f'bootstrap_primary = "{members[0]}"\n'
            "sync = true\n"
            "sync_timeout_ms = 10000\n"
        )
    members_block = "\n".join(_member(m) for m in members)
    return (
        "[[data_plane.group]]\n"
        f'name = "{name}"\n'
        f"worker_count = {WORKER_THREADS}\n\n"
        f"{mode_block}\n"
        f"{members_block}\n"
    )


def single_node_configs() -> dict:
    return {"node1": _header("node1")}


def raft_configs() -> dict:
    nodes = ["node1", "node2", "node3"]
    body = (
        _identity(nodes[0])
        + "\n[data_plane]\nrebalance_interval_ms = 0\n\n"
        + _group("grp-1", "raft", nodes)
    )
    return {n: _header(n) + body.replace(f'name = "{nodes[0]}"', f'name = "{n}"', 1) for n in nodes}


def stream_configs() -> dict:
    nodes = ["node1", "node2"]
    body = (
        _identity(nodes[0])
        + "\n[data_plane]\nrebalance_interval_ms = 0\n\n"
        + _group("grp-1", "stream", nodes)
    )
    return {n: _header(n) + body.replace(f'name = "{nodes[0]}"', f'name = "{n}"', 1) for n in nodes}


def scale_out_configs() -> dict:
    control = ["ctrl1", "ctrl2", "ctrl3"]
    groups = [
        ("grp-1", ["node1", "node2", "node3"]),
        ("grp-2", ["node4", "node5", "node6"]),
    ]
    all_nodes = control + [m for _, members in groups for m in members]

    control_block = "[control_plane.replica.raft]\n\n" + "\n".join(
        _control_member(c) for c in control
    )
    groups_block = "\n".join(_group(gname, "raft", members) for gname, members in groups)

    template = (
        _identity(control[0])
        + "\n"
        + control_block
        + "\n[data_plane]\nrebalance_interval_ms = 0\n\n"
        + groups_block
    )
    return {
        n: _header(n) + template.replace(f'name = "{control[0]}"', f'name = "{n}"', 1)
        for n in all_nodes
    }


SCENARIO_CONFIGS = {
    "single-node": single_node_configs,
    "raft": raft_configs,
    "stream": stream_configs,
    "scale-out": scale_out_configs,
}

# Deployment shapes: scenario -> (services to start, comma-separated node list
# for the driver). Control nodes are started but never listed for the driver;
# the driver connects to data nodes only (in scale-out the DDL is submitted
# through a data node to the control plane).
SCENARIO_SERVICES = {
    "single-node": "node1",
    "raft": "node1 node2 node3",
    "stream": "node1 node2",
    "scale-out": "ctrl1 ctrl2 ctrl3 node1 node2 node3 node4 node5 node6",
}
SCENARIO_NODES = {
    "single-node": "node1",
    "raft": "node1,node2,node3",
    "stream": "node1,node2",
    "scale-out": "node1,node2,node3,node4,node5,node6",
}

DEFAULT_SCENARIOS = "single-node,raft,stream,scale-out"


def _compose(args: list, **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["docker", "compose", "-f", str(E2E_DIR / "compose.yaml"), *args],
        **kwargs,
    )


def _log(msg: str) -> None:
    print(f"==> {msg}", file=sys.stderr, flush=True)


def prepare_caches() -> None:
    """Create persistent external caches; scenario cleanup only removes test data."""
    result = _compose(["config", "--format", "json"], check=True, capture_output=True, text=True)
    for volume in json.loads(result.stdout)["volumes"].values():
        if volume.get("external"):
            subprocess.run(
                ["docker", "volume", "create", volume["name"]],
                check=True,
                stdout=subprocess.DEVNULL,
            )


def build_images() -> None:
    _log(f"building dev image {DEV_IMAGE} (first run is slow)")
    subprocess.run(
        ["docker", "build", "-f", str(REPO_ROOT / "Dockerfile.dev"), "-t", DEV_IMAGE, str(REPO_ROOT)],
        check=True,
    )

    _log(f"building the mudud binary image {E2E_IMAGE}")
    subprocess.run(
        ["docker", "build", "-f", str(E2E_DIR / "Dockerfile.e2e"), "-t", E2E_IMAGE, str(REPO_ROOT)],
        check=True,
    )


def prepare_wallet() -> None:
    _log("preparing the packaged example app (wallet.mpk)")
    wallet_mpk = REPO_ROOT / "target" / "wasm32-wasip2" / "release" / "wallet.mpk"
    if not wallet_mpk.exists():
        subprocess.run(["cargo", "make", "package-wallet"], cwd=REPO_ROOT, check=True)
    shutil.copy(wallet_mpk, E2E_DIR / "wallet.mpk")


def generate_configs(scenario: str) -> None:
    configs = SCENARIO_CONFIGS[scenario]()
    CONFIGS_DIR.mkdir(parents=True, exist_ok=True)
    for old in CONFIGS_DIR.glob("*.toml"):
        old.unlink()
    for name, content in configs.items():
        (CONFIGS_DIR / f"{name}.toml").write_text(content, encoding="utf-8")


def wait_ready(services: str) -> None:
    _log("waiting for node readiness")
    for service in services.split():
        for _ in range(60):
            probe = _compose(
                ["exec", "-T", service, "bash", "-c", "exec 3<>/dev/tcp/127.0.0.1/8300"],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
            if probe.returncode == 0:
                break
            time.sleep(1)
        else:
            raise RuntimeError(f"node readiness timed out: {service}")


def run_scenario(scenario: str) -> None:
    services = SCENARIO_SERVICES[scenario]
    nodes = SCENARIO_NODES[scenario]

    _log(f"scenario {scenario}: generating configs and starting nodes")
    generate_configs(scenario)

    try:
        _compose(["up", "-d", *services.split()], check=True)
        wait_ready(services)

        _log(f"running the client driver (nodes: {nodes})")
        _compose(
            [
                "run",
                "--rm",
                "-e",
                f"MUDUDB_E2E_SCENARIO={scenario}",
                "-e",
                f"MUDUDB_E2E_NODES={nodes}",
                "driver",
            ],
            check=True,
        )
    finally:
        _compose(["logs", "--no-color"], check=False)
        _compose(["down", "--volumes"], check=True)


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--scenario",
        default=DEFAULT_SCENARIOS,
        help=f"comma-separated deployment shapes to run (default: {DEFAULT_SCENARIOS})",
    )
    parser.add_argument('--stage', choices=['images', 'wallet', 'caches', 'scenario', 'cleanup'], help=argparse.SUPPRESS)
    add_options(parser, 'distributed-e2e')
    parser.epilog = ('Images/wallet/caches are prerequisites. Each scenario saves node logs and cleans up; '
                     'cleanup failure blocks later scenarios. Docker target caches remain isolated.')
    args = parser.parse_args(normalized_argv())

    scenarios = [s.strip() for s in args.scenario.split(",") if s.strip()]
    unknown = [s for s in scenarios if s not in SCENARIO_CONFIGS]
    if unknown:
        parser.error(f"unknown scenario(s): {', '.join(unknown)}")

    if not scenarios:
        parser.error('select at least one scenario')
    if args.stage:
        if args.stage == 'scenario':
            run_scenario(scenarios[0])
        elif args.stage == 'cleanup':
            _compose(['down', '--volumes'], check=True)
        else:
            {'images': build_images, 'wallet': prepare_wallet, 'caches': prepare_caches}[args.stage]()
        return 0
    report = Report(args, 'MuduDB distributed e2e')
    base = [sys.executable, __file__]
    report.run('images', base + ['--stage', 'images'])
    report.run('wallet', base + ['--stage', 'wallet'])
    report.run('caches', base + ['--stage', 'caches'])
    dependencies = ['images', 'wallet', 'caches']
    for scenario in scenarios:
        report.run(scenario, base + ['--stage', 'scenario', '--scenario', scenario], needs=dependencies)
        # Recheck teardown independently even if the scenario itself failed.
        # A failed cleanup blocks the next scenario from using a dirty environment.
        if not report.stopped and all(any(r['name'] == d and r['status'] == 'passed'
                                         for r in report.results) for d in dependencies):
            cleanup = f'cleanup-{scenario}'
            report.run(cleanup, base + ['--stage', 'cleanup'])
            dependencies = ['images', 'wallet', 'caches', cleanup]
    return report.finish()



if __name__ == "__main__":
    sys.exit(main())
